//! Escalation bundles: when the implementation model hits its iteration limit, `aegis escalate <TASK>` packs a
//! deterministic context for a stronger model — the task packet, the model's escalation report, the current fast-gate
//! output and the working-tree diff. Which model receives it is the harness's decision; the bundle states the rules
//! (bounded attempts, then a human).

use anyhow::{Context, Result};
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::profile::Profile;
use crate::tasks::TASKS_DIR;

pub const BUNDLE_DIR: &str = "target/aegis/escalations";

/// Keeps the first `head` and last `tail` lines of long output.
pub fn truncate(text: &str, head: usize, tail: usize) -> String {
    let lines: Vec<&str> = text.lines().collect();
    if lines.len() <= head + tail {
        return text.to_string();
    }
    format!(
        "{}\n… [{} lines omitted] …\n{}",
        lines[..head].join("\n"),
        lines.len() - head - tail,
        lines[lines.len() - tail..].join("\n")
    )
}

/// Runs the profile's fast gate with this binary, colour off, and returns stdout+stderr.
pub fn run_fast_gate(root: &Path, profile_rel: &str, profile: &Profile) -> Result<String> {
    let exe = std::env::current_exe().context("cannot locate the aegis binary")?;
    let out = Command::new(exe)
        .args(["gate", "--profile", profile_rel, "--only", &profile.agent_loop().fast_stages.join(",")])
        .current_dir(root)
        .env("NO_COLOR", "1")
        .env("CLICOLOR", "0")
        .env("CARGO_TERM_COLOR", "never")
        .output()
        .context("cannot run the fast gate")?;
    Ok(format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr)))
}

fn git(root: &Path, args: &[&str]) -> String {
    Command::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).to_string())
        .unwrap_or_default()
}

/// Writes target/aegis/escalations/<TASK>.md. `gate_output`: `None` runs the fast gate now.
pub fn bundle(root: &Path, profile: &Profile, profile_rel: &str, task: &str, gate_output: Option<String>) -> Result<PathBuf> {
    let task_id = if task.starts_with("TASK-") { task.to_string() } else { format!("TASK-{}", task) };
    let artifact = task_id.trim_start_matches("TASK-").to_string();
    let task_path = root.join(TASKS_DIR).join(format!("{}.md", task_id));
    let packet = std::fs::read_to_string(&task_path)
        .with_context(|| format!("{} not found — run `aegis tasks` first", task_path.display()))?;
    let report_path = root.join(format!("ESCALATION-{}.md", artifact));
    let report = std::fs::read_to_string(&report_path)
        .unwrap_or_else(|_| format!("_No `{}` written by the implementation model._", report_path.display()));
    let gate = match gate_output {
        Some(g) => g,
        None => run_fast_gate(root, profile_rel, profile)?,
    };
    let excludes = [":(exclude)doc", ":(exclude)tools/aegis", ":(exclude)target"];
    let mut diff_args = vec!["diff", "HEAD", "--", "."];
    diff_args.extend(excludes);
    let diff = git(root, &diff_args);
    let mut status_args = vec!["status", "--porcelain", "--", "."];
    status_args.extend(excludes);
    let untracked: Vec<String> = git(root, &status_args)
        .lines()
        .filter_map(|l| l.strip_prefix("?? "))
        .map(String::from)
        .collect();
    let mut untracked_text = String::new();
    for f in &untracked {
        if let Ok(content) = std::fs::read_to_string(root.join(f)) {
            untracked_text.push_str(&format!("### {} (new file)\n\n```\n{}\n```\n\n", f, truncate(&content, 150, 50)));
        }
    }
    let attempts = profile.agent_loop().escalation_attempts;
    let fast = format!("aegis gate --profile {} --only {}", profile_rel, profile.agent_loop().fast_stages.join(","));
    let out = format!(
        "# Escalation Context: {task_id}\n\n\
         > Generated by `aegis escalate` — deterministic bundle for a stronger model.\n\n\
         ## Instructions for the Receiving Model\n\n\
         The implementation model reached its iteration limit on this task. You get at most **{attempts} attempts**: \
         change production code, run `{fast}`, read the full output. Same constraints as the task packet: frozen tests, \
         `doc/` and `tools/aegis` are read-only. If the root cause is a specification or test defect, do not work around \
         it — write the blocking question for the human instead. After {attempts} unsuccessful attempts, stop: a human decides.\n\n\
         ## Task Packet\n\n{packet}\n\n\
         ## Escalation Report of the Implementation Model\n\n{report}\n\n\
         ## Current Fast-Gate Output\n\n```text\n{}\n```\n\n\
         ## Working-Tree Diff vs HEAD (excluding doc/, tools/aegis, target/)\n\n```diff\n{}\n```\n\n{untracked_text}",
        truncate(&gate, 250, 100),
        if diff.trim().is_empty() { "(no changes to tracked files)".to_string() } else { truncate(&diff, 400, 100) },
    );
    let dir = root.join(BUNDLE_DIR);
    std::fs::create_dir_all(&dir)?;
    let path = dir.join(format!("{}.md", task_id));
    std::fs::write(&path, out)?;
    Ok(path)
}
